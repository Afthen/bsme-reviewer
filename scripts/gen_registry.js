/**
 * scripts/gen_registry.js
 * Auto-discovers all leaf topic manifests under src/topics/ and emits
 * the flat lazy registry at src/topics/index.js.
 */

import fs from "node:fs";
import path from "node:path";
import { pathToFileURL } from "node:url";

const TOPICS_ROOT = path.resolve("src/topics");
const OUT_FILE = path.join(TOPICS_ROOT, "index.js");

function findLeafIndexes(dir, acc = []) {
  for (const entry of fs.readdirSync(dir, { withFileTypes: true })) {
    if (entry.name === "common" || entry.name === "node_modules") continue;
    const full = path.join(dir, entry.name);
    if (entry.isDirectory()) {
      findLeafIndexes(full, acc);
    } else if (entry.name === "index.js" && dir !== TOPICS_ROOT) {
      acc.push(full);
    }
  }
  return acc;
}

function isTopicManifest(val) {
  return Boolean(
    val &&
    typeof val === "object" &&
    typeof val.id === "string" &&
    typeof val.title === "string" &&
    typeof val.subject === "string" &&
    val.varsDb &&
    Array.isArray(val.relations) &&
    typeof val.createSystem === "function"
  );
}

const entries = [];
const seenIds = new Set();

for (const file of findLeafIndexes(TOPICS_ROOT).sort()) {
  const mod = await import(pathToFileURL(file).href);
  const found = Object.entries(mod).find(([, v]) => isTopicManifest(v));
  if (!found) {
    throw new Error(`Leaf index does not export a valid topic object: ${file}`);
  }

  const [exportName, topic] = found;
  if (seenIds.has(topic.id)) {
    throw new Error(`Duplicate topic id "${topic.id}" found in ${file}`);
  }
  seenIds.add(topic.id);

  const relImport = "./" + path.relative(TOPICS_ROOT, file).replace(/\\/g, "/");
  entries.push({
    id: topic.id,
    title: topic.title,
    subject: topic.subject,
    category: topic.category ?? null,
    exportName,
    relImport
  });
}

entries.sort((a, b) => a.id.localeCompare(b.id));

const manifestLines = entries
  .map(e => `  Object.freeze(${JSON.stringify({ id: e.id, title: e.title, subject: e.subject, category: e.category })})`)
  .join(",\n");

const loaderLines = entries
  .map(e => `  ${JSON.stringify(e.id)}: () => import(${JSON.stringify(e.relImport)}).then(m => m.${e.exportName})`)
  .join(",\n");

const output = `/**
 * src/topics/index.js
 * AUTO-GENERATED by scripts/gen_registry.js — do not edit by hand.
 */

export const TOPIC_MANIFEST = Object.freeze([
${manifestLines}
]);

const MANIFEST_IDS = new Set(TOPIC_MANIFEST.map(m => m.id));

const LOADERS = Object.freeze({
${loaderLines}
});

const CACHE = new Map();

export function hasTopic(id) {
  return MANIFEST_IDS.has(id);
}

export async function loadTopic(id) {
  if (CACHE.has(id)) return CACHE.get(id);
  const loader = LOADERS[id];
  if (!loader) return null;
  const topic = await loader();
  CACHE.set(id, topic);
  return topic;
}

export async function loadTopics(ids = []) {
  const loaded = await Promise.all(ids.map(loadTopic));
  return loaded.filter(Boolean);
}

export async function loadAllTopics() {
  return loadTopics(TOPIC_MANIFEST.map(m => m.id));
}
`;

fs.writeFileSync(OUT_FILE, output, "utf8");
console.log(`Generated src/topics/index.js (${entries.length} topics).`);
