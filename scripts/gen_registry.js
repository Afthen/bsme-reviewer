/**
 * scripts/gen_registry.js
 * Auto-discovers all leaf topic manifests under src/topics/ and emits
 * the flat lazy registry at src/topics/index.js.
 */

import fs from "node:fs";
import path from "node:path";
import { pathToFileURL } from "node:url";

const TOPICS_ROOT = path.resolve("src/topics");
const OUT_FILE = path.join(TOPICS_ROOT, "index.js");
const MCQ_ROOT = path.resolve("src/mcq");
const MCQ_OUT_FILE = path.join(MCQ_ROOT, "index.js");

function findLeafIndexes(dir, acc = []) {
  for (const entry of fs.readdirSync(dir, { withFileTypes: true })) {
    if (entry.name === "common" || entry.name === "node_modules") continue;
    const full = path.join(dir, entry.name);
    if (entry.isDirectory()) {
      findLeafIndexes(full, acc);
    } else if (entry.name === "index.js" && dir !== TOPICS_ROOT) {
      acc.push(full);
    }
  }
  return acc;
}

function isTopicManifest(val) {
  return Boolean(
    val &&
    typeof val === "object" &&
    typeof val.id === "string" &&
    typeof val.title === "string" &&
    typeof val.subject === "string" &&
    val.varsDb &&
    Array.isArray(val.relations) &&
    typeof val.createSystem === "function"
  );
}

const entries = [];
const seenIds = new Set();

for (const file of findLeafIndexes(TOPICS_ROOT).sort()) {
  const mod = await import(pathToFileURL(file).href);
  const found = Object.entries(mod).find(([, v]) => isTopicManifest(v));
  if (!found) {
    throw new Error(`Leaf index does not export a valid topic object: ${file}`);
  }

  const [exportName, topic] = found;
  if (seenIds.has(topic.id)) {
    throw new Error(`Duplicate topic id "${topic.id}" found in ${file}`);
  }
  seenIds.add(topic.id);

  const relImport = "./" + path.relative(TOPICS_ROOT, file).replace(/\\/g, "/");
  entries.push({
    id: topic.id,
    title: topic.title,
    subject: topic.subject,
    category: topic.category ?? null,
    exportName,
    relImport
  });
}

entries.sort((a, b) => a.id.localeCompare(b.id));

const manifestLines = entries
  .map(e => `  Object.freeze(${JSON.stringify({ id: e.id, title: e.title, subject: e.subject, category: e.category })})`)
  .join(",\n");

const loaderLines = entries
  .map(e => `  ${JSON.stringify(e.id)}: () => import(${JSON.stringify(e.relImport)}).then(m => m.${e.exportName})`)
  .join(",\n");

const output = `/**
 * src/topics/index.js
 * AUTO-GENERATED by scripts/gen_registry.js — do not edit by hand.
 */

export const TOPIC_MANIFEST = Object.freeze([
${manifestLines}
]);

const MANIFEST_IDS = new Set(TOPIC_MANIFEST.map(m => m.id));

const LOADERS = Object.freeze({
${loaderLines}
});

const CACHE = new Map();

export function hasTopic(id) {
  return MANIFEST_IDS.has(id);
}

export async function loadTopic(id) {
  if (CACHE.has(id)) return CACHE.get(id);
  const loader = LOADERS[id];
  if (!loader) return null;
  const topic = await loader();
  CACHE.set(id, topic);
  return topic;
}

export async function loadTopics(ids = []) {
  const loaded = await Promise.all(ids.map(loadTopic));
  return loaded.filter(Boolean);
}

export async function loadAllTopics() {
  return loadTopics(TOPIC_MANIFEST.map(m => m.id));
}
`;

fs.writeFileSync(OUT_FILE, output, "utf8");
console.log(`Generated src/topics/index.js (${entries.length} topics).`);

// --- Auto-discover MCQ sets under src/mcq/ ---
function findMcqJsonFiles(dir, acc = []) {
  if (!fs.existsSync(dir)) return acc;
  for (const entry of fs.readdirSync(dir, { withFileTypes: true })) {
    if (entry.name === "assets" || entry.name === "node_modules") continue;
    const full = path.join(dir, entry.name);
    if (entry.isDirectory()) {
      findMcqJsonFiles(full, acc);
    } else if (entry.name.endsWith(".json") && dir !== MCQ_ROOT) {
      acc.push(full);
    }
  }
  return acc;
}

function titleFromSlug(slug) {
  return slug
    .replace(/\.json$/i, "")
    .replace(/[_-]+/g, " ")
    .replace(/\b\w/g, c => c.toUpperCase());
}

const mcqEntries = [];
const seenMcqIds = new Set();

for (const file of findMcqJsonFiles(MCQ_ROOT).sort()) {
  const raw = JSON.parse(fs.readFileSync(file, "utf8"));
  const relDir = path.relative(MCQ_ROOT, path.dirname(file)).replace(/\\/g, "/");
  const parts = relDir.split("/").filter(Boolean);
  const subject = raw.subject || titleFromSlug(parts[0] || "General");
  const category = raw.category ?? (parts.length >= 3 ? titleFromSlug(parts[1]) : null);
  const id = raw.id || `mcq_${relDir.replace(/\//g, "_")}`;
  const title = raw.title || raw.setName || titleFromSlug(parts[parts.length - 1] || path.basename(file));

  if (seenMcqIds.has(id)) {
    throw new Error(`Duplicate MCQ set id "${id}" found in ${file}`);
  }
  seenMcqIds.add(id);

  const relPath = "./" + path.relative(MCQ_ROOT, file).replace(/\\/g, "/");
  const baseDir = "./" + (relDir ? `${relDir}/` : "");
  mcqEntries.push({
    id,
    title,
    subject,
    category,
    count: Array.isArray(raw.questions) ? raw.questions.length : 0,
    relPath,
    baseDir
  });
}

mcqEntries.sort((a, b) => a.id.localeCompare(b.id));

const mcqManifestLines = mcqEntries
  .map(e => `  Object.freeze(${JSON.stringify({ id: e.id, title: e.title, subject: e.subject, category: e.category, count: e.count })})`)
  .join(",\n");

const mcqPathLines = mcqEntries
  .map(e => `  ${JSON.stringify(e.id)}: Object.freeze({ relPath: ${JSON.stringify(e.relPath)}, baseDir: ${JSON.stringify(e.baseDir)} })`)
  .join(",\n");

const mcqOutput = `/**
 * src/mcq/index.js
 * AUTO-GENERATED by scripts/gen_registry.js — do not edit by hand.
 */

export const MCQ_MANIFEST = Object.freeze([
${mcqManifestLines}
]);

const MANIFEST_BY_ID = new Map(MCQ_MANIFEST.map(m => [m.id, m]));
const PATHS = Object.freeze({
${mcqPathLines}
});
const CACHE = new Map();

export function hasMcqSet(id) {
  return MANIFEST_BY_ID.has(id);
}

export async function loadMcqSet(id) {
  if (CACHE.has(id)) return CACHE.get(id);
  const entry = PATHS[id];
  const meta = MANIFEST_BY_ID.get(id);
  if (!entry || !meta) return null;

  const fileUrl = new URL(entry.relPath, import.meta.url);
  let data;
  if (typeof process !== "undefined" && process.versions?.node) {
    const { readFileSync } = await import("node:fs");
    data = JSON.parse(readFileSync(fileUrl, "utf8"));
  } else {
    const res = await fetch(fileUrl);
    if (!res.ok) throw new Error(\`Failed to load MCQ set \${id}: \${res.status}\`);
    data = await res.json();
  }

  const baseUrl = new URL(entry.baseDir, import.meta.url).href;
  const setObj = Object.freeze({
    ...meta,
    baseUrl,
    questions: Array.isArray(data.questions) ? data.questions : []
  });
  CACHE.set(id, setObj);
  return setObj;
}

export async function loadMcqSets(ids = []) {
  const loaded = await Promise.all(ids.map(loadMcqSet));
  return loaded.filter(Boolean);
}
`;

fs.mkdirSync(MCQ_ROOT, { recursive: true });
fs.writeFileSync(MCQ_OUT_FILE, mcqOutput, "utf8");
console.log(`Generated src/mcq/index.js (${mcqEntries.length} MCQ sets).`);
